<?php

declare(strict_types=1);

namespace Scraper\ScraperJeuxVideo\Tests\Request;

use Scraper\ScraperJeuxVideo\Model\Game;
use Scraper\ScraperJeuxVideo\Request\JeuxVideoGameRequest;
use Symfony\Contracts\HttpClient\ResponseInterface;

/**
 * @internal
 */
final class JeuxVideoGameRequestTest extends AbstractRequestTestCase
{
    public function testJeuxVideoSearchGameRequest(): void
    {
        $client = $this->getClient('game.json');

        $request = new JeuxVideoGameRequest('partner', 'hash');
        $request
            ->setId(1237618)
            ->setMachineId(22)
        ;

        $result = $client->send($request);

        $this->assertInstanceOf(Game::class, $result);
    }

    public function testUserReviewAverageDecimalAcceptsFloat(): void
    {
        $client = $this->getClient('game.json');

        $request = new JeuxVideoGameRequest('partner', 'hash');
        $request
            ->setId(1237618)
            ->setMachineId(22)
        ;

        /** @var Game $result */
        $result = $client->send($request);

        $this->assertSame(15.5, $result->reviews?->userReviewAverageDecimal);
    }

    public function requestCallback(string $method, string $url, array $options): ResponseInterface
    {
        $this->assertEquals('GET', $method);
        $this->assertEquals('https://api.jeuxvideo.com/v4/games/1237618/22', $url);
        $this->assertIsArray($options);

        return parent::requestCallback($method, $url, $options); // TODO: Change the autogenerated stub
    }
}
